                <p>Years passed. The garage became a shop. The shop became a fixture. Tom's daughter, Sarah, joined the business after university, bringing fresh ideas but the same old values. More mechanics came on board — riders themselves, people who knew the sting of a puncture at the top of Honister Pass, the satisfaction of a perfectly tuned derailleur.</p>

                <p>When Alf was gone, the silence he left behind was too big to ignore. Tom did the only thing that made sense — he renamed the shop in Alf's honour, not as a memorial, but as a continuation. This place stands in memory of a cat who chose loyalty over comfort, who sat through countless repairs without complaint, who reminded everyone that the best things in life aren't owned — they're earned through showing up, day after day.</p>

                <p>Every bike worked on here carries a little of that story forward. Every spoke tightened, every chain cleaned, every conversation over the counter. And if you look closely — really closely — you might still imagine Alf there, sitting tall on a saddle, one paw stretched out, ruling the place like he always did.</p>
